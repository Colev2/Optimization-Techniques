function x_proj = Projection(x, Restraints)
% Προβάλλει το διάνυσμα x στο σύνολο που ορίζεται 
% από τους περιορισμούς Restraints.

% Restraints: πίνακας Nx2
%   - 1η στήλη: κατώτατο όριο κάθε μεταβλητής
%   - 2η στήλη: ανώτατο όριο κάθε μεταβλητής
%
% Η προβολή γίνεται "ανα διάσταση":
%   Αν μια συντεταγμένη x(i) είναι μικρότερη από το κάτω όριο,
%       παίρνει την τιμή του κάτω ορίου.
%   Αν είναι μεγαλύτερη από το πάνω όριο,
%       παίρνει την τιμή του πάνω ορίου.
%   Αλλιώς μένει ως έχει.

    % Αρχικοποίηση
    x_proj = x;

    % Για κάθε διάσταση εφαρμόζουμε τις αντίστοιχες δεσμεύσεις
    for i = 1:size(Restraints, 1)
        
        lowerBound = Restraints(i, 1);
        upperBound = Restraints(i, 2);

        % Αν x(i) είναι κάτω από το όριο, το "κόβουμε" στο κάτω όριο
        if x(i) < lowerBound
            x_proj(i) = lowerBound;

        % Αν x(i) είναι πάνω από το όριο, το "κόβουμε" στο πάνω όριο
        elseif x(i) > upperBound
            x_proj(i) = upperBound;
        end
        % Αν βρίσκεται ανάμεσα στα όρια, δεν κάνουμε τίποτα
    end
end
