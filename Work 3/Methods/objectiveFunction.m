function f = objectiveFunction(x, y)
    % Η συναρτηση καλειται με 1 ορισμα απο τους αλγοριθμους, και με 2
    % ορισματα απο την plot για τη σχεδιαση. Οποτε, βαζουμε εναν ελεγχο που
    % λεει οτι αν κληθεις με 1 ορισμα, τοτε αυτο θα ειναι διανυσμα με x1
    % την πρωτη συντεταγμενη και x2 την δευτερη.
    
    if nargin == 1   
        x1 = x(1);
        x2 = x(2);
        f = (1/3)*x1.^2 + 3*x2.^2;
    else
        f = (1/3)*x.^2 + 3*y.^2;
    end

end